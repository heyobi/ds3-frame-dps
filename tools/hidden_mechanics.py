#!/usr/bin/env python3
"""List mechanics that the game data shows but the in-game menus (and the usual motion-value sheet) do not.

usage: python3 tools/hidden_mechanics.py --weapons DS3InventoryBuilder/DataGenerator/Raw > results/hidden_mechanics.md

1. Attacks whose elemental motion value differs from the physical one (AtkParam_Pc *Correction fields), for
   elements the weapon can actually carry (base element of unique weapons, or an infusion's element).
2. Hidden stamina multiplier per weapon (EquipParamWeapon.StaminaConsumeRate), extremes per weapon class.
3. R1 swings with two hitbox phases that have different motion values.
"""
import argparse, collections, csv, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import moves as MV

ap = argparse.ArgumentParser()
ap.add_argument("--weapons", required=True)
ap.add_argument("--regulation", default="data/regulation_extract.json")
ap.add_argument("--frames", default="data/ds3_frames_full.txt")
args = ap.parse_args()
R = json.load(open(args.regulation)); B, W = R["behaviors"], R["weapons"]
SKIP = {"Shield", "Small Shield", "Greatshield", "Staff", "Talisman", "Sacred Chime", "Bow", "Greatbow", "Crossbow",
        "Pyromancy Flame", "Torch"}
EL = ["physical", "magic", "fire", "lightning", "dark"]
names, cls, elems = {}, {}, collections.defaultdict(lambda: collections.defaultdict(set))
for r in csv.reader(open(f"{args.weapons}/weapons_10.csv")):
    bid = int(r[0]) // 10000
    if r[3] == "-":
        names[bid], cls[bid] = r[1], r[2]
    for e, c in enumerate((178, 179, 180, 181, 182)):
        if float(r[c]) > 0:
            elems[bid][e].add("base" if r[3] == "-" else r[3])


def group(j):
    j = int(j)
    for lim, name in ((100, "1H R1 / running / rolling"), (200, "1H R2"), (300, "2H R1 / running / rolling"),
                      (400, "2H R2"), (500, "other (4xx)"), (600, "other (5xx)"), (700, "L1 / left hand"),
                      (10000, "weapon art")):
        if j < lim:
            return name


print("# Hidden mechanics in the DS3 game data\n")
print("Generated by `tools/hidden_mechanics.py` from the regulation (App 1.15.2, Regulation 1.35).\n")
print("## 1. Attacks where an element does not scale like the physical part\n")
print("Each attack's damage per element = AR of that element x its motion value (`AtkParam_Pc` `Atk*Correction`). "
      "Normally all elements share the physical motion value. Rows below differ, for elements the weapon can carry "
      "(`base` = unique weapon's own element, otherwise the infusions that add it).\n")
print("| Weapon | Attacks | Element | Physical MV | Element MV | Element comes from |")
print("|---|---|---|---|---|---|")
for bid, nm in sorted(names.items(), key=lambda kv: kv[1]):
    w = W.get(str(bid * 10000))
    if not w or cls[bid] in SKIP:
        continue
    var, base = str(w["var"]), str(w["cat"] * 100)
    rows = collections.defaultdict(list)
    for j in sorted(set(B.get(var, {})) | set(B.get(base, {})), key=int):
        b = B.get(var, {}).get(j) or B.get(base, {}).get(j)
        cor = b[1:6]
        if max(cor) == 0:
            continue
        for e in range(1, 5):
            if elems[bid][e] and cor[e] != cor[0]:
                rows[(group(j), EL[e], cor[0] == 0, cor[e] == 0)].append((int(j), cor[0], cor[e]))
    for (g, el, phys0, el0), hits in rows.items():
        src = "/".join(sorted(elems[bid][EL.index(el)]))
        pm = sorted({h[1] for h in hits}); em = sorted({h[2] for h in hits})
        fmt = lambda v: str(v[0]) if len(v) == 1 else f"{v[0]}-{v[-1]}"
        print(f"| {nm} | {g} ({len(hits)}) | {el} | {fmt(pm)} | {fmt(em)} | {src} |")

print("\n## 2. Hidden stamina multiplier\n")
print("Every attack's stamina cost is multiplied by the weapon's `StaminaConsumeRate`, which the game never shows. "
      "Weapons of the same class share base costs, so this is the only difference. Classes where it varies:\n")
print("| Class | Cheapest | Most expensive | Others |")
print("|---|---|---|---|")
by = collections.defaultdict(list)
for bid, nm in names.items():
    w = W.get(str(bid * 10000))
    if w and cls[bid] not in SKIP:
        by[cls[bid]].append((w["scr"], nm))
for c, v in sorted(by.items()):
    v.sort()
    if v[-1][0] - v[0][0] < 0.05:
        continue
    mid = ", ".join(f"{n} x{s:.2f}" for s, n in v[1:-1] if abs(s - 1) > 0.001)
    print(f"| {c} | {v[0][1]} x{v[0][0]:.2f} | {v[-1][1]} x{v[-1][0]:.2f} | {mid} |")

print("\n## 3. R1 swings with a weaker lead-in phase\n")
print("These R1s carry two hitbox phases with different motion values. A target hit by the early part of the "
      "swing takes the lower value; the DPS tables use the stronger one.\n")
print("| Weapon | Chain | Lead-in MV | Main MV |")
print("|---|---|---|---|")
tae, wcat = MV.load_frames(args.frames)
for bid, nm in sorted(names.items(), key=lambda kv: kv[1]):
    w = W.get(str(bid * 10000))
    if not w or cls[bid] in SKIP or bid not in wcat:
        continue
    cat, sp = wcat[bid]
    for key, label in (("r1h", "1H R1"), ("r2h", "2H R1")):
        steps = MV.chain(tae, cat, sp, key)
        if not steps:
            continue
        pairs = set()
        for cancel, judges in steps:
            mvs = []
            for j in judges:
                b = MV.behavior(R, w["var"], w["cat"], j)
                if b and b[1] > 0:
                    mvs.append(b[1])
            if len(mvs) > 1 and len(set(mvs)) > 1:
                pairs.add((mvs[0], max(mvs)))
        for lead, main in sorted(pairs):
            if lead < main:
                print(f"| {nm} | {label} | {lead} | {main} |")
